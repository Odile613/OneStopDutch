/**
 * Generate the JS mirror of the backend prompts and model catalogue so the
 * Netlify AI Function uses exactly the same configuration as server/chat_api.py.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (relative) => readFile(path.join(root, relative), "utf8");

const [vocab, grammar, models] = await Promise.all([
  read("server/prompts/vocab.md"),
  read("server/prompts/grammar.md"),
  read("server/models.json"),
]);

const outDir = path.join(root, "netlify/functions/_lib");
await mkdir(outDir, { recursive: true });
await writeFile(
  path.join(outDir, "generated.mjs"),
  "// Generated by scripts/generate-function-assets.mjs — do not edit by hand.\n" +
    `export const VOCAB_SYSTEM_PROMPT = ${JSON.stringify(vocab.trim())};\n` +
    `export const GRAMMAR_SYSTEM_PROMPT = ${JSON.stringify(grammar.trim())};\n` +
    `export const MODEL_CONFIG = ${JSON.stringify(JSON.parse(models), null, 2)};\n`,
  "utf8",
);

console.log("Generated netlify/functions/_lib/generated.mjs");
